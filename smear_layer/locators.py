def norm(s): return re.sub(r'\s+',' ',s).replace('- ','').strip()
def find(key):
    f,ph = L[key]; path,off,cite = F[f]
    if isinstance(off,tuple):
        import fitz
        d=fitz.open(path); n=norm(ph)
        for i,pg in enumerate(d):
            if n in norm(pg.get_text()): return i+1,None
        return None,None
    txt = open(path,encoding='utf8').read()
    # split by page markers
    parts = re.split(r'(?:<!-- PDF page (\d+) -->|===== PAGE (\d+) =====)', txt)
    pages={}; cur=None
    for i in range(1,len(parts),3):
        cur = int(parts[i] or parts[i+1]); pages[cur]=pages.get(cur,'')+' '+parts[i+2]
    n=norm(ph).replace('- ','')
    hits=[p for p,t in pages.items() if n in norm(t)]
    if not hits:
        # try joined across page
        ks=sorted(pages)
        for a,b in zip(ks,ks[1:]):
            if n in norm(pages[a]+' '+pages[b]): return a,None
    return (hits[0] if hits else None),None
